#!/usr/bin/env node
// Makes every Tangent logo file from the one mark (design/logo/tangent-mark.svg, the graduation fold): the reversed mark, the
// app icon and favicon tiles, the admin's and console's favicons, the web parts' path (packages/web-ui/src/tangent-mark.ts),
// and the Android and iPhone launcher icons. Run after changing the mark: node tools/gen-logo.mjs
import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const write = (p, s) => writeFileSync(new URL(p, root), s);
const mark = read('design/logo/tangent-mark.svg');
const viewBox = /viewBox="([^"]+)"/.exec(mark)[1];
const d = /\sd="([^"]+)"/.exec(mark)[1];
const [vx, vy, vw, vh] = viewBox.split(/\s+/).map(Number);
const INK = '#111111';
const ON_INK = '#FFFFFF';

/** The mark on its ink tile, `size` square: `share` of the width is the mark, `radius` the corner (0 for a store icon). */
function tile(size, { share = 0.7, radius = size * 0.22, background = INK } = {}) {
  const w = size * share;
  const h = (w * vh) / vw;
  const bg = background ? `<rect width="${size}" height="${size}" rx="${radius}" fill="${background}"/>` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">${bg}<svg x="${(size - w) / 2}" y="${(size - h) / 2}" width="${w}" height="${h}" viewBox="${viewBox}"><path fill="${ON_INK}" fill-rule="evenodd" d="${d}"/></svg></svg>`;
}

write('design/logo/tangent-mark-reversed.svg', `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"><path fill="#FFFFFF" fill-rule="evenodd" d="${d}"/></svg>\n`);
write('design/logo/tangent-app-icon.svg', `${tile(64, { radius: 14 })}\n`);
write('design/logo/tangent-favicon.svg', `${tile(64, { share: 0.8, radius: 12 })}\n`);

// The web parts draw the mark from its path (TangentIcon).
write('packages/web-ui/src/tangent-mark.ts', `// Generated by tools/gen-logo.mjs from design/logo/tangent-mark.svg. Do not edit.
/** The Tangent mark (the graduation fold): its view box and one even-odd path. */
export const MARK_VIEW_BOX = '${viewBox}';
export const MARK_PATH = '${d}';
`);

// The admin's and the console's tab icon.
const favicon = `data:image/svg+xml,${encodeURIComponent(tile(64, { share: 0.8, radius: 12 }))}`;
for (const app of ['apps/admin/index.html', 'apps/console/index.html']) {
  const html = read(app);
  write(app, html.replace(/<link rel="icon"[^>]*>/, `<link rel="icon" href="${favicon}" />`));
}

// Launcher icons, drawn by a browser so the curves render exactly as the SVG says.
const browser = await chromium.launch();
const page = await browser.newPage();
async function png(svg, size, file, transparent = false) {
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(`<html><body style="margin:0;background:transparent">${svg}</body></html>`);
  await page.locator('svg').first().screenshot({ path: new URL(file, root).pathname.replace(/^\/([A-Za-z]:)/, '$1'), omitBackground: transparent });
}
const ANDROID = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [dpi, size] of Object.entries(ANDROID)) {
  await png(tile(size), size, `android/app/src/main/res/mipmap-${dpi}/ic_launcher.png`, true);
  // The adaptive icon's foreground: the mark alone in the middle 66 of 108, on the ink background colour.
  const fg = Math.round((size * 108) / 48);
  await png(tile(fg, { share: 0.5, background: null }), fg, `android/app/src/main/res/mipmap-${dpi}/ic_launcher_foreground.png`, true);
}
// iPhone icons are square and opaque: iOS rounds the corners itself.
const ios = JSON.parse(read('ios/Runner/Assets.xcassets/AppIcon.appiconset/Contents.json'));
for (const img of ios.images) {
  if (!img.filename) continue;
  const size = Math.round(Number(img.size.split('x')[0]) * Number(img.scale.replace('x', '')));
  await png(tile(size, { radius: 0 }), size, `ios/Runner/Assets.xcassets/AppIcon.appiconset/${img.filename}`);
}
await browser.close();
console.log('Wrote the Tangent logo files from design/logo/tangent-mark.svg.');
