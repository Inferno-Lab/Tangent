// Writes the app's list of languages (lib/core/translations/languages.dart) from packages/contracts (LANGUAGE_LIST), so the
// app's picker and the server agree. The app reads everything else from the school's /v1/config.
// Run after changing the languages:  pnpm --filter @tangent/contracts build && node tools/gen-app-config.mjs
// The languages a school may offer, as the app shows them in its picker (contracts LANGUAGE_LIST, one list for every surface).
import { LANGUAGE_LIST, scriptFont } from '../packages/contracts/dist/index.js';
import { writeFileSync } from 'node:fs';

// Script fonts the app fetches from the server (apps/api/assets/fonts); Devanagari and Arabic are bundled, CJK uses the phone's own.
const BUNDLED = new Set(['Noto Sans Devanagari', 'Noto Sans Arabic', 'Noto Nastaliq Urdu']);
const fetched = Object.fromEntries(LANGUAGE_LIST.map((l) => [l.code, scriptFont(l.code)]).filter(([, f]) => f && !BUNDLED.has(f) && !/ (SC|JP|KR)$/.test(f)).map(([c, f]) => [c, f.replace(/ /g, '')]));
const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
writeFileSync(new URL('../lib/core/translations/languages.dart', import.meta.url), `// Generated by tools/gen-app-config.mjs from packages/contracts/src/i18n.ts (LANGUAGE_LIST). Do not edit.

/// Every language a school may offer the app, by its own name (as its speakers pick it). Direction comes with the locale.
const kLanguageNames = <String, String>{
${LANGUAGE_LIST.map((l) => `  ${q(l.code)}: ${q(l.own)},`).join('\n')}
};

/// The Noto font a language's script needs that the app does not bundle, fetched from the school's server on first use.
const kLanguageFonts = <String, String>{
${Object.entries(fetched).map(([c, f]) => `  ${q(c)}: ${q(f)},`).join('\n')}
};

/// Those fonts' families, in every text role's fallback list (a family not yet loaded is skipped).
const kScriptFonts = <String>[${[...new Set(Object.values(fetched))].map(q).join(', ')}];

/// Every language code, for the app's supported locales.
const kAppLanguages = <String>[${LANGUAGE_LIST.map((l) => q(l.code)).join(', ')}];
`);
console.log('wrote lib/core/translations/languages.dart');
